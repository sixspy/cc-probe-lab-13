"""写闸：强制结栏的闸形态登记与结栏/灌入共享的进程写锁。

- 闸形态必须显式选定：无闸/野闸回刷在路由与结栏服务两层都被拒绝。
- 正式结：水位过阈才允许，物化进站点汇总账（正式轨）。
- 强制结：未过阈只写只读归档凭证（影子轨），不产生正式汇总行。
- 写锁串行化结栏与灌入，杜绝半栏双写/双成功。
"""
from __future__ import annotations
import threading

正式结 = "正式结"
强制结 = "强制结"
闸形态集 = (正式结, 强制结)

# 结栏与灌入共用一把写锁：同票同成败、不并发抢写。
写锁 = threading.RLock()


def 校验闸形态(闸: str | None) -> str:
    if 闸 not in 闸形态集:
        raise ValueError("须显式选定写闸形态：正式结或强制结，拒绝无闸结栏回刷")
    return 闸
